// Recorre el flujo completo (onboarding → resultado → plan → paywall → login) a 375px y guarda capturas.
import { chromium } from '@playwright/test';
const base = process.argv[2] ?? 'http://localhost:3100';
const out = 'docs/revisiones/flujo';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 });
const errores = [];
p.on('console', (m) => { if (m.type() === 'error') errores.push(m.text()); });
p.on('pageerror', (e) => errores.push(String(e)));
const shot = async (n, full = false) => { await p.waitForTimeout(500); await p.screenshot({ path: `${out}/${n}.png`, fullPage: full }); console.log('captura', n); };

await p.goto(`${base}/onboarding?qa=1`, { waitUntil: 'networkidle' });
await shot('00-nombre');
await p.getByPlaceholder('Mateo').fill('Mateo');
await p.getByRole('button', { name: 'Continuar' }).click();
await p.waitForTimeout(600);
await shot('01-objetivo');
await p.getByRole('button', { name: /Definir/ }).click();
await p.waitForTimeout(700);
await shot('01b-dolor');
await p.getByRole('button', { name: /no ve el aceite/ }).click();
await p.waitForTimeout(700);
await p.getByRole('button', { name: 'Hombre' }).click();
await p.getByLabel('Edad').fill('28');
await p.getByLabel('Estatura').fill('178');
await p.getByLabel('Peso actual').fill('82');
await p.getByLabel(/Peso meta/).fill('76');
await shot('02-datos');
await p.getByRole('button', { name: 'Continuar' }).click();
await p.waitForTimeout(500);
await shot('03-actividad');
await p.getByRole('button', { name: /5 a 6 días/ }).click();
await p.waitForTimeout(700);
await shot('04-foto');
await p.getByRole('button', { name: /Usar una foto de ejemplo/ }).click();
await p.waitForTimeout(1800);
await shot('05-analizando');
await p.getByText('¿Y el aceite?').waitFor({ timeout: 15000 });
await shot('06-resultado-antes', true);
// validación: intentar continuar sin datos no debe romper

await p.getByRole('button', { name: /1 cucharada/ }).click();
await p.waitForTimeout(900);
await shot('07-resultado-despues', true);
await p.getByRole('button', { name: 'Ver mi plan' }).click();
await p.waitForTimeout(2600);
await shot('08-plan');
await p.getByText(/tu plan de bajar grasa está listo/).waitFor({ timeout: 15000 });
await p.waitForTimeout(1200);
await shot('08b-diagnostico', true);
await p.getByRole('button', { name: /Ver mi plan y empezar la prueba/ }).click();
await p.waitForURL('**/paywall', { timeout: 12000 });
await p.waitForTimeout(1500);
await shot('09-paywall');
await p.screenshot({ path: `${out}/09-paywall-completo.png`, fullPage: true });
await p.getByRole('button', { name: /Empezar mis 7 días gratis/ }).click();
await p.waitForURL('**/entrar**');
await p.waitForTimeout(600);
await shot('10-login');
// El envío del código es REAL (Supabase + Resend): el script se detiene aquí para no mandar correos de prueba.
const eventos = await p.evaluate(() => JSON.parse(sessionStorage.getItem('ns_eventos') ?? '[]').map((e) => e.evento));
console.log('eventos', eventos.join(','));
console.log('errores de consola:', errores.length ? errores : 'ninguno');
await b.close();
